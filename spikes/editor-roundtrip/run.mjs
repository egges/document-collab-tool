// Markdown round-trip test for candidate editors. See README.md.
//
// For every file in corpus/ and every editor it checks:
//   1. open + save: is the saved file identical to the original? If not, did
//      only the spelling change, or did the rendered result change too?
//   2. stability: does saving an already-saved file change it again?
//   3. small edit: after one word is changed in an already-saved file, how many
//      lines differ? Ideally exactly one.
//
// Writes the saved files to results/<editor>/ and a summary to results/REPORT.md.
import { mkdirSync, readdirSync, readFileSync, writeFileSync, rmSync } from "node:fs";
import { join } from "node:path";
import { micromark } from "micromark";
import { gfm, gfmHtml } from "micromark-extension-gfm";
import { createTwoFilesPatch, diffLines } from "diff";
import { editors } from "./editors.mjs";

const CORPUS = "corpus";
const RESULTS = "results";

// --- What a page means, independent of how its Markdown is spelled --------

const FRONTMATTER = /^---\n([\s\S]*?)\n---\n/;

// The page rendered to HTML by a reference CommonMark + GFM parser. Two files
// with the same rendering differ only in Markdown spelling.
function render(md) {
  const fm = md.match(FRONTMATTER);
  const body = fm ? md.slice(fm[0].length) : md;
  const html = micromark(body, {
    allowDangerousHtml: true,
    extensions: [gfm()],
    htmlExtensions: [gfmHtml()],
  });
  const normal = html.replace(/>\s+</g, "><").replace(/\s+/g, " ").trim();
  return (fm ? `[frontmatter ${fm[1].replace(/\s+/g, " ")}]` : "") + normal;
}

// The visible text of the page, without any markup.
function visibleText(md) {
  return render(md)
    .replace(/<[^>]*>/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

function classify(original, saved) {
  if (saved === original) return "identical";
  if (saved.trimEnd() === original.trimEnd()) return "whitespace";
  if (render(saved) === render(original)) return "spelling";
  if (visibleText(saved) === visibleText(original)) return "structure";
  return "text";
}

const LABEL = {
  identical: "identical",
  whitespace: "trailing whitespace only",
  spelling: "rewritten, renders the same",
  structure: "rendering changed",
  text: "**visible text changed**",
};

function changedLines(a, b) {
  let n = 0;
  for (const part of diffLines(a, b)) if (part.added || part.removed) n += part.count;
  return n;
}

function patch(name, a, b) {
  return createTwoFilesPatch(`original/${name}`, `saved/${name}`, a, b, "", "", { context: 1 })
    .split("\n")
    .slice(2) // drop the "===" header and the index line
    .join("\n");
}

// --- Run --------------------------------------------------------------------

const files = readdirSync(CORPUS).filter((f) => f.endsWith(".md")).sort();
rmSync(RESULTS, { recursive: true, force: true });

const results = [];
for (const editor of editors) {
  mkdirSync(join(RESULTS, editor.id), { recursive: true });
  for (const file of files) {
    const original = readFileSync(join(CORPUS, file), "utf8");
    const r = { editor, file, original };
    try {
      r.once = await editor.save(await editor.open(original));
      r.twice = await editor.save(await editor.open(r.once));
      const doc = await editor.open(r.once);
      r.word = editor.editWord(doc);
      r.edited = r.word ? await editor.save(doc) : null;
      writeFileSync(join(RESULTS, editor.id, file), r.once);
    } catch (err) {
      r.error = String(err?.stack ?? err);
    }
    results.push(r);
  }
}

// --- Report -----------------------------------------------------------------

const out = [];
out.push("# Editor round-trip results", "");
out.push("Generated by `npm test`. Each corpus file is opened and saved with no edits.", "");

for (const editor of editors) {
  const rows = results.filter((r) => r.editor === editor);
  out.push(`## ${editor.name}`, "");
  out.push("| File | Open + save | Lines changed | Saving again changes it | Lines changed by a one-word edit |");
  out.push("|---|---|---:|---|---:|");
  const tally = {};
  for (const r of rows) {
    if (r.error) {
      out.push(`| ${r.file} | **error** | | | |`);
      tally.error = (tally.error ?? 0) + 1;
      continue;
    }
    const kind = classify(r.original, r.once);
    tally[kind] = (tally[kind] ?? 0) + 1;
    const stable = r.twice === r.once ? "no" : `**yes** (${changedLines(r.once, r.twice)} lines)`;
    const edit = r.edited == null ? "n/a" : changedLines(r.once, r.edited);
    out.push(
      `| ${r.file} | ${LABEL[kind]} | ${changedLines(r.original, r.once)} | ${stable} | ${edit} |`,
    );
  }
  out.push("");
  out.push(
    "Summary: " +
      Object.entries(tally)
        .map(([k, v]) => `${v} ${k === "error" ? "errors" : LABEL[k].replaceAll("*", "")}`)
        .join(", ") +
      ".",
    "",
  );

  out.push("<details><summary>Diffs</summary>", "");
  for (const r of rows) {
    if (r.error) {
      out.push(`### ${r.file}`, "", "```", r.error, "```", "");
    } else if (r.once !== r.original) {
      out.push(`### ${r.file}`, "", "```diff", patch(r.file, r.original, r.once), "```", "");
    }
  }
  out.push("</details>", "");
}

mkdirSync(RESULTS, { recursive: true });
writeFileSync(join(RESULTS, "REPORT.md"), out.join("\n"));

// Short console summary.
for (const editor of editors) {
  const rows = results.filter((r) => r.editor === editor && !r.error);
  const errors = results.filter((r) => r.editor === editor && r.error).length;
  const count = (k) => rows.filter((r) => classify(r.original, r.once) === k).length;
  const unstable = rows.filter((r) => r.twice !== r.once).length;
  console.log(
    `${editor.name.padEnd(38)} identical ${count("identical") + count("whitespace")}/${files.length}` +
      `  same rendering ${count("spelling")}  rendering changed ${count("structure")}` +
      `  text changed ${count("text")}  unstable ${unstable}  errors ${errors}`,
  );
}
console.log(`\nDetails: ${join(RESULTS, "REPORT.md")}`);
